    required String quizExplain,
  }) {
    return BankingLesson(
      id: id,
      title: title,
      titleUrdu: titleUrdu,
      introduction: introduction,
      meaning: meaning,
      whyUsed: whyUsed,
      steps: steps,
      commonMistakes: mistakes,
      safetyAdvice: safety,
      practicePrompt: practice,
